'use strict';

var fs = require('fs');
var path = require('path');

var getStringWidth;
try {
    getStringWidth = require('internal/util/inspect').getStringWidth; // eslint-disable-line global-require
} catch (e) {}

if (typeof getStringWidth !== 'function' || !process.versions.icu) {
    throw new Error('this script must be run with `node --expose-internals`, on a version of node built with ICU');
}

var ranges = [];
var current = null;
for (var codePoint = 0; codePoint <= 0x10FFFF; codePoint++) {
    if (codePoint < 0xD800 || codePoint > 0xDFFF) {
        // node measures ASCII itself, and only passes the rest of the string to ICU
        var width = codePoint < 127 ? Number(codePoint >= 32) : getStringWidth(String.fromCodePoint(codePoint), false);
        var previousEnd = codePoint === 0xE000 ? 0xD7FF : codePoint - 1;
        if (current && current.width === width && current.end === previousEnd) {
            current.end = codePoint;
        } else {
            current = {
                end: codePoint,
                start: codePoint,
                width: width
            };
            ranges.push(current);
        }
    }
}

var lastEnd = -1;
var tokens = [];
for (var i = 0; i < ranges.length; i++) {
    if (ranges[i].width !== 1) {
        tokens.push(ranges[i].width + (ranges[i].start - lastEnd - 1).toString(36) + '.' + (ranges[i].end - ranges[i].start).toString(36));
        lastEnd = ranges[i].end;
    }
}

var lines = [];
var line = '';
for (var j = 0; j < tokens.length; j++) {
    var piece = tokens[j] + (j < tokens.length - 1 ? ',' : '');
    if (line.length + piece.length > 100) {
        lines.push(line);
        line = '';
    }
    line += piece;
}
lines.push(line);

var source = [
    '/*',
    ' * generated by `npm run generate:string-width`; do not edit.',
    ' * display widths of code points, as computed by node\'s ICU-based `getStringWidth`, for Unicode ' + process.versions.unicode + '.',
    ' * every code point not in a range has width 1. each comma-separated range is: its width, then (in base 36) the gap since the previous range ended, a dot, and its length minus 1.',
    ' */',
    '',
    'var $join = Array.prototype.join;',
    '',
    'module.exports = $join.call([',
    lines.map(function (l) { return '    \'' + l + '\''; }).join(',\n'),
    '], \'\');',
    ''
].join('\n');

if (process.argv[2] === '--stdout') {
    process.stdout.write(source);
} else {
    fs.writeFileSync(path.join(__dirname, '..', 'stringWidthRanges.js'), source);
}
